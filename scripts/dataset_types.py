#!/usr/bin/env python3
"""Write stories/datasets/datasets.d.ts: a TypeScript type for each `virtual:dataset/<name>`.

    python3 scripts/dataset_types.py            # fetches each dataset by its SOURCE.json URL
    python3 scripts/dataset_types.py DIR        # or reads <DIR>/<name>.json instead

The data is not in this repository, so its shape is described here instead, from the published
file itself; the sha256 in SOURCE.json is checked before a type is written. Re-run it whenever a
reduce.py changes what it writes. Stdlib only.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATASETS = ROOT / "stories" / "datasets"


def ts(v, indent=2) -> str:
    pad = " " * indent
    if isinstance(v, bool):
        return "boolean"
    if isinstance(v, (int, float)) or v is None:
        return "number" if v is not None else "null"
    if isinstance(v, str):
        return "string"
    if isinstance(v, list):
        if not v:
            return "unknown[]"
        kinds = sorted({ts(x, indent) for x in v})
        inner = kinds[0] if len(kinds) == 1 else "(" + " | ".join(kinds) + ")"
        return f"{inner}[]"
    fields = []
    for k, x in v.items():
        key = k if re.fullmatch(r"[A-Za-z_$][\w$]*", k) else json.dumps(k)
        fields.append(f"{pad}{key}: {ts(x, indent + 2)}")
    return "{\n" + "\n".join(fields) + "\n" + " " * (indent - 2) + "}"


def main() -> int:
    local = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    out = ["// GENERATED by scripts/dataset_types.py from the published datasets -- do not hand-edit.", ""]
    for d in sorted(p for p in DATASETS.iterdir() if (p / "SOURCE.json").exists()):
        src = json.loads((d / "SOURCE.json").read_text())
        body = (local / f"{d.name}.json").read_bytes() if local else urllib.request.urlopen(src["url"]).read()
        if hashlib.sha256(body).hexdigest() != src["data_sha256"]:
            raise SystemExit(f"{d.name}: data does not match SOURCE.json's sha256; not describing it")
        out += [f'declare module "virtual:dataset/{d.name}" {{',
                f"  const data: {ts(json.loads(body), 4)}",
                "  export default data", "}", ""]
    (DATASETS / "datasets.d.ts").write_text("\n".join(out))
    print(f"wrote {DATASETS / 'datasets.d.ts'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
